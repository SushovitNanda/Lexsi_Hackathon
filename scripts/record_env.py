"""Fill ENV.md's version table and write ENV-local.txt from the venv."""
import importlib.metadata as md, platform, subprocess, sys, torch
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
pk = ["torch", "transformers", "peft", "bitsandbytes", "accelerate", "datasets", "safetensors", "sentencepiece",
      "huggingface_hub", "curatorkit", "auditkit", "safetune", "circuitkit", "transformer_lens",
      "IndicTransToolkit", "gguf", "sentence-transformers", "detoxify"]
rows = []
for p in pk:
    try:
        rows.append((p, md.version(p)))
    except md.PackageNotFoundError:
        rows.append((p, "MISSING"))
commits = {k: subprocess.run(["git", "-C", str(ROOT / "KITS" / k), "rev-parse", "HEAD"], capture_output=True,
                             text=True).stdout.strip() for k in ("CuratorKIT", "SafeTune", "CircuitKIT")}
lines = ["# ENV.md — pinned versions (Sushovit, local)", "",
         "Colab's first cell must pin the same `transformers`, `peft`, `bitsandbytes`, `accelerate`, `datasets`,",
         "`auditkit` and kit commits. Generated by `scripts/record_env.py`.", "", "| Item | Value |", "|---|---|",
         f"| OS | {platform.platform()} (no WSL) |",
         "| GPU | NVIDIA GeForce RTX 4080 Laptop GPU, 12 GB, driver 595.79 |", "| RAM | 32 GB |",
         f"| Python | {sys.version.split()[0]} (`C:\\lexsi\\.venv`) |",
         f"| CUDA (torch) | {torch.version.cuda} |"]
lines += [f"| {p} | {v} |" for p, v in rows]
lines += [f"| {k} commit | {v} |" for k, v in commits.items()]
pins = {p: v for p, v in rows if p in ("transformers", "peft", "bitsandbytes", "accelerate", "datasets", "auditkit")}
lines += ["", "Colab pin line:", "```", "!pip install -q " + " ".join(f'"{p}=={v}"' for p, v in pins.items() if v != "MISSING"), "```"]
(ROOT / "ENV.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
freeze = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True).stdout
(ROOT / "ENV-local.txt").write_text(freeze, encoding="utf-8")
print("\n".join(lines))
